-- TEMPLATE 9: MONITORING AND ALERTING SETUP
-- Set up performance monitoring
-- =============================================================================

-- Create performance monitoring table
CREATE TABLE IF NOT EXISTS public.performance_logs (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    metric_name text NOT NULL,
    metric_value numeric,
    recorded_at timestamptz NOT NULL DEFAULT now(),
    metadata jsonb
);

-- Create function to log performance metrics
CREATE OR REPLACE FUNCTION log_performance_metric(
    p_metric_name text,
    p_metric_value numeric,
    p_metadata jsonb DEFAULT NULL
)
RETURNS void AS $$
BEGIN
    INSERT INTO public.performance_logs (metric_name, metric_value, metadata)
    VALUES (p_metric_name, p_metric_value, p_metadata);
END;
$$ LANGUAGE plpgsql;

-- Create indexes for performance logs
CREATE INDEX IF NOT EXISTS idx_performance_logs_metric_time 
ON public.performance_logs(metric_name, recorded_at DESC);

