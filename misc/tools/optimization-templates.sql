-- TEMPLATE 8: VACUUM AND MAINTENANCE
-- Regular maintenance tasks for optimal performance
-- =============================================================================

-- Note: These are typically run outside of migrations
-- Create monitoring function to check maintenance needs

CREATE OR REPLACE FUNCTION check_maintenance_needs()
RETURNS TABLE(
    table_name text,
    dead_tuples bigint,
    live_tuples bigint,
    bloat_percent numeric,
    last_vacuum timestamptz,
    recommendation text
) AS $$
BEGIN
    RETURN QUERY
    SELECT 
        schemaname || '.' || tablename as table_name,
        n_dead_tup,
        n_live_tup,
        CASE 
            WHEN n_live_tup > 0 THEN 
                round((n_dead_tup::numeric / n_live_tup::numeric) * 100, 2)
            ELSE 0
        END as bloat_percent,
        last_vacuum,
        CASE 
            WHEN n_dead_tup > n_live_tup * 0.2 THEN 'URGENT: Manual VACUUM needed'
            WHEN n_dead_tup > n_live_tup * 0.1 THEN 'Consider VACUUM'
            ELSE 'Healthy'
        END as recommendation
    FROM pg_stat_user_tables 
    ORDER BY bloat_percent DESC;
END;
$$ LANGUAGE plpgsql;

