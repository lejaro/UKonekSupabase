-- TEMPLATE 6: MATERIALIZED VIEWS FOR COMPLEX AGGREGATIONS
-- Use for frequently accessed aggregated data
-- =============================================================================

-- Create materialized view for dashboard metrics
CREATE MATERIALIZED VIEW IF NOT EXISTS public.dashboard_metrics AS
SELECT 
    date_trunc('day', created_at) as date,
    count(*) as total_records,
    count(*) FILTER (WHERE status = 'completed') as completed_count,
    avg(processing_time) as avg_processing_time
FROM public.transactions
WHERE created_at >= CURRENT_DATE - INTERVAL '30 days'
GROUP BY date_trunc('day', created_at)
ORDER BY date DESC;

-- Create index on materialized view
CREATE INDEX IF NOT EXISTS idx_dashboard_metrics_date 
ON public.dashboard_metrics(date DESC);

-- Create function to refresh materialized view
CREATE OR REPLACE FUNCTION refresh_dashboard_metrics()
RETURNS void AS $$
BEGIN
    REFRESH MATERIALIZED VIEW CONCURRENTLY public.dashboard_metrics;
END;
$$ LANGUAGE plpgsql;

