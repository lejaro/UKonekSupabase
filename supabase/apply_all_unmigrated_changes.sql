-- 1.1 Add drug_classification column to medicines
ALTER TABLE public.medicines
  ADD COLUMN IF NOT EXISTS drug_classification text NOT NULL DEFAULT 'rx'
    CHECK (drug_classification IN ('rx', 'otc'));

CREATE INDEX IF NOT EXISTS idx_medicines_classification
  ON public.medicines (drug_classification);

-- 1.2 Mark common known over-the-counter medications as 'otc'
UPDATE public.medicines
SET drug_classification = 'otc'
WHERE LOWER(TRIM(name)) IN (
  'paracetamol', 'ibuprofen', 'cetirizine', 'ascorbic acid', 'vitamin c',
  'multivitamins', 'oral rehydration salts', 'ors', 'antacid',
  'aluminum hydroxide', 'magnesium hydroxide', 'loratadine',
  'salbutamol syrup', 'carbocisteine', 'mefenamic acid'
)
AND drug_classification = 'rx';

