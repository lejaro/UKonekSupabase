create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_role text;
  v_family_number text;
  v_no_family_yet boolean;
  v_family_id bigint;
begin
  v_role := lower(coalesce(new.raw_user_meta_data->>'role', ''));

  if lower(coalesce(new.email, '')) = 'admin@ukonek.local' then
    insert into public.staff (
      first_name,
      middle_name,
      last_name,
      birthday,
      gender,
      username,
      employee_id,
      email,
      role,
      consent_given,
      status,
      auth_user_id
    ) values (
      'System',
      '-',
      'Admin',
      date '1990-01-01',
      'Prefer not to say',
      'admin',
      '01',
      'admin@ukonek.local',
      'admin',
      true,
      'Active',
      new.id
    )
    on conflict (email)
    do update set
      role = excluded.role,
      status = excluded.status,
      auth_user_id = excluded.auth_user_id;

    return new;
  end if;

  if v_role = 'citizen' then
    v_family_number := public.normalize_family_number(new.raw_user_meta_data->>'family_number');
    v_no_family_yet := lower(trim(coalesce(new.raw_user_meta_data->>'no_family_yet', 'false'))) in ('1', 'true', 'yes', 'y');

    if v_no_family_yet then
      v_family_id := null;
    elsif v_family_number is not null then
      v_family_id := public.ensure_family(v_family_number, new.raw_user_meta_data->>'complete_address');
    else
      v_family_id := null;
      v_no_family_yet := true;
    end if;

    insert into public.citizens (
      firstname,
      surname,
      middle_initial,
      date_of_birth,
      age,
      contact_number,
      sex,
      email,
      complete_address,
      emergency_contact_complete_name,
      emergency_contact_contact_number,
      relation,
      family_id,
      family_status,
      username,
      role,
      auth_user_id
    ) values (
      coalesce(new.raw_user_meta_data->>'firstname', ''),
      coalesce(new.raw_user_meta_data->>'surname', ''),
      new.raw_user_meta_data->>'middle_initial',
      (new.raw_user_meta_data->>'date_of_birth')::date,
      (new.raw_user_meta_data->>'age')::integer,
      new.raw_user_meta_data->>'contact_number',
      new.raw_user_meta_data->>'sex',
      new.email,
      new.raw_user_meta_data->>'complete_address',
      new.raw_user_meta_data->>'emergency_contact_complete_name',
      new.raw_user_meta_data->>'emergency_contact_contact_number',
      new.raw_user_meta_data->>'relation',
      v_family_id,
      case
        when v_family_id is null then 'NO_FAMILY_YET'::public.family_status_enum
        else 'HAS_FAMILY'::public.family_status_enum
      end,
      new.raw_user_meta_data->>'username',
      'citizen',
      new.id
    )
    on conflict (email)
    do update set
      firstname = excluded.firstname,
      surname = excluded.surname,
      middle_initial = excluded.middle_initial,
      date_of_birth = excluded.date_of_birth,
      age = excluded.age,
      contact_number = excluded.contact_number,
      sex = excluded.sex,
      complete_address = excluded.complete_address,
      emergency_contact_complete_name = excluded.emergency_contact_complete_name,
      emergency_contact_contact_number = excluded.emergency_contact_contact_number,
      relation = excluded.relation,
      family_id = excluded.family_id,
      family_status = excluded.family_status,
      username = excluded.username,
      auth_user_id = excluded.auth_user_id;
  end if;

  return new;
end;
$$;

create or replace function public.api_get_citizens(
  p_name text default null,
  p_family_number text default null,
  p_family_status text default null
)
returns table (
  id bigint,
  username text,
  firstname text,
  surname text,
  email text,
  contact_number text,
  family_id bigint,
  family_number text,
  family_status text,
  created_at timestamptz
)
language sql
security definer
set search_path = public
as $$
  select
    c.id,
    c.username,
    c.firstname,
    c.surname,
    c.email,
    c.contact_number,
    c.family_id,
    f.family_number,
    c.family_status::text,
    c.created_at
  from public.citizens c
  left join public.families f on f.id = c.family_id
  where
    (
      nullif(trim(coalesce(p_name, '')), '') is null
      or lower(concat_ws(' ', coalesce(c.firstname, ''), coalesce(c.surname, ''), coalesce(c.username, ''))) like '%' || lower(trim(p_name)) || '%'
    )
    and (
      nullif(trim(coalesce(p_family_number, '')), '') is null
      or f.family_number = public.normalize_family_number(p_family_number)
    )
    and (
      nullif(trim(coalesce(p_family_status, '')), '') is null
      or c.family_status::text = upper(trim(p_family_status))
    )
  order by c.created_at desc;
$$;

grant execute on function public.api_get_citizens(text, text, text) to authenticated;

create or replace function public.api_get_families(
  p_family_number text default null,
  p_name text default null
)
returns table (
  id bigint,
  family_number text,
  address text,
  created_at timestamptz,
  member_count bigint
)
language sql
security definer
set search_path = public
as $$
  select
    f.id,
    f.family_number,
    f.address,
    f.created_at,
    count(c.id)::bigint as member_count
  from public.families f
  left join public.citizens c on c.family_id = f.id
  where
    (
      nullif(trim(coalesce(p_family_number, '')), '') is null
      or f.family_number = public.normalize_family_number(p_family_number)
    )
    and (
      nullif(trim(coalesce(p_name, '')), '') is null
      or exists (
        select 1
        from public.citizens c2
        where c2.family_id = f.id
          and lower(concat_ws(' ', coalesce(c2.firstname, ''), coalesce(c2.surname, ''), coalesce(c2.username, ''))) like '%' || lower(trim(p_name)) || '%'
      )
    )
  group by f.id, f.family_number, f.address, f.created_at
  order by f.family_number asc;
$$;

grant execute on function public.api_get_families(text, text) to authenticated;

create or replace function public.api_get_family_by_id(p_family_id bigint)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_result jsonb;
begin
  select jsonb_build_object(
    'id', f.id,
    'family_number', f.family_number,
    'address', f.address,
    'created_at', f.created_at,
    'members', coalesce(
      (
        select jsonb_agg(
          jsonb_build_object(
            'id', c.id,
            'username', c.username,
            'firstname', c.firstname,
            'surname', c.surname,
            'email', c.email,
            'contact_number', c.contact_number,
            'family_status', c.family_status::text,
            'created_at', c.created_at
          )
          order by c.created_at desc
        )
        from public.citizens c
        where c.family_id = f.id
      ),
      '[]'::jsonb
    )
  )
  into v_result
  from public.families f
  where f.id = p_family_id;

  return coalesce(v_result, jsonb_build_object('error', 'Family not found.'));
end;
$$;

grant execute on function public.api_get_family_by_id(bigint) to authenticated;

create or replace function public.api_upsert_citizen_family_assignment(
  p_citizen_id bigint,
  p_mode text,
  p_existing_family_id bigint default null,
  p_new_family_number text default null,
  p_new_family_address text default null
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_mode text;
  v_family_id bigint;
  v_exists boolean;
begin
  v_mode := upper(trim(coalesce(p_mode, '')));

  if p_citizen_id is null then
    return jsonb_build_object('ok', false, 'error', 'Citizen id is required.');
  end if;

  select exists (select 1 from public.citizens c where c.id = p_citizen_id)
  into v_exists;

  if not v_exists then
    return jsonb_build_object('ok', false, 'error', 'Citizen not found.');
  end if;

  if v_mode = 'NO_FAMILY_YET' then
    v_family_id := null;
  elsif v_mode = 'EXISTING_FAMILY' then
    if p_existing_family_id is null then
      return jsonb_build_object('ok', false, 'error', 'Existing family id is required.');
    end if;

    select f.id into v_family_id
    from public.families f
    where f.id = p_existing_family_id;

    if v_family_id is null then
      return jsonb_build_object('ok', false, 'error', 'Selected family does not exist.');
    end if;
  elsif v_mode = 'CREATE_FAMILY' then
    v_family_id := public.ensure_family(p_new_family_number, p_new_family_address);
    if v_family_id is null then
      return jsonb_build_object('ok', false, 'error', 'Family number is required for new family.');
    end if;
  else
    return jsonb_build_object('ok', false, 'error', 'Invalid mode. Use NO_FAMILY_YET, EXISTING_FAMILY, or CREATE_FAMILY.');
  end if;

  update public.citizens c
  set
    family_id = v_family_id,
    family_status = case
      when v_family_id is null then 'NO_FAMILY_YET'::public.family_status_enum
      else 'HAS_FAMILY'::public.family_status_enum
    end
  where c.id = p_citizen_id;

  return jsonb_build_object('ok', true, 'family_id', v_family_id);
end;
$$;

grant execute on function public.api_upsert_citizen_family_assignment(bigint, text, bigint, text, text) to authenticated;
