-- Refactor citizen family model to explicit families + family_status.
--
-- Migration goals:
-- 1) Create normalized families table.
-- 2) Migrate existing citizens.family_number values to families rows.
-- 3) Enforce explicit citizen family state:
--    - family_id is null  => family_status = 'NO_FAMILY_YET'
--    - family_id is set   => family_status = 'HAS_FAMILY'
-- 4) Provide RPCs for web/backend list/filter/update flows.

create table if not exists public.families (
  id bigint generated by default as identity primary key,
  family_number varchar(100) not null unique,
  address text,
  created_at timestamptz not null default now(),
  constraint families_family_number_not_blank check (nullif(trim(family_number), '') is not null)
);

create index if not exists idx_families_family_number on public.families (family_number);

alter table public.families enable row level security;

drop policy if exists families_select_active_staff on public.families;
create policy families_select_active_staff
  on public.families
  for select
  using (
    exists (
      select 1
      from public.staff s
      where s.auth_user_id = auth.uid()
        and lower(trim(coalesce(s.status, ''))) = 'active'
    )
  );

grant select on public.families to authenticated;

do $$
begin
  if not exists (
    select 1
    from pg_type t
    join pg_namespace n on n.oid = t.typnamespace
    where n.nspname = 'public'
      and t.typname = 'family_status_enum'
  ) then
    create type public.family_status_enum as enum ('HAS_FAMILY', 'NO_FAMILY_YET');
  end if;
end;
$$;

alter table public.citizens
  add column if not exists family_id bigint,
  add column if not exists family_status public.family_status_enum;

do $$
begin
  if not exists (
    select 1
    from pg_constraint
    where conname = 'citizens_family_id_fkey'
      and conrelid = 'public.citizens'::regclass
  ) then
    alter table public.citizens
      add constraint citizens_family_id_fkey
      foreign key (family_id)
      references public.families(id)
      on delete set null;
  end if;
end;
$$;

create or replace function public.normalize_family_number(p_value text)
returns text
language plpgsql
immutable
as $$
declare
  v_value text;
begin
  v_value := upper(trim(coalesce(p_value, '')));
  if v_value = '' then
    return null;
  end if;
  return v_value;
end;
$$;

create or replace function public.ensure_family(
  p_family_number text,
  p_address text default null
)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  v_family_id bigint;
  v_family_number text;
  v_address text;
begin
  v_family_number := public.normalize_family_number(p_family_number);
  v_address := nullif(trim(coalesce(p_address, '')), '');

  if v_family_number is null then
    return null;
  end if;

  insert into public.families (family_number, address)
  values (v_family_number, v_address)
  on conflict (family_number)
  do update
    set address = coalesce(public.families.address, excluded.address)
  returning id into v_family_id;

  return v_family_id;
end;
$$;

-- Data migration notes:
-- - Existing non-empty citizens.family_number values are normalized and inserted into public.families.
-- - Citizens are then linked to family_id.
-- - Records without a family number are explicitly marked NO_FAMILY_YET.
do $$
begin
  if exists (
    select 1
    from information_schema.columns
    where table_schema = 'public'
      and table_name = 'citizens'
      and column_name = 'family_number'
  ) then
    insert into public.families (family_number)
    select distinct public.normalize_family_number(c.family_number)
    from public.citizens c
    where public.normalize_family_number(c.family_number) is not null
    on conflict (family_number) do nothing;

    update public.citizens c
    set family_id = f.id
    from public.families f
    where public.normalize_family_number(c.family_number) = f.family_number
      and c.family_id is null;
  end if;
end;
$$;

update public.citizens
set family_status = case
  when family_id is null then 'NO_FAMILY_YET'::public.family_status_enum
  else 'HAS_FAMILY'::public.family_status_enum
end;

