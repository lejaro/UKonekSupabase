-- 4. RPC: Inventory Report
-- ============================================================

create or replace function public.get_inventory_report()
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_result jsonb;
  v_total_medicines bigint;
  v_total_stock bigint;
  v_low_stock_count bigint;
  v_expiring_count bigint;
  v_expired_count bigint;
  v_category_breakdown jsonb;
  v_recent_transactions jsonb;
begin
  select count(*), coalesce(sum(m.qty), 0)
  into v_total_medicines, v_total_stock
  from public.medicines m where m.archived_at is null;

  select count(*) into v_low_stock_count
  from public.medicines m
  where m.archived_at is null and m.qty <= m.reorder_level;

  select count(*) into v_expiring_count
  from public.medicines m
  where m.archived_at is null
    and m.expiration_date is not null
    and m.expiration_date between current_date and (current_date + 90);

  select count(*) into v_expired_count
  from public.medicines m
  where m.archived_at is null
    and m.expiration_date is not null
    and m.expiration_date < current_date;

  select coalesce(jsonb_agg(row_to_json(cb)), '[]'::jsonb)
  into v_category_breakdown
  from (
    select m.category, count(*) as count, coalesce(sum(m.qty), 0) as total_qty
    from public.medicines m where m.archived_at is null
    group by m.category order by count desc
  ) cb;

  select coalesce(jsonb_agg(row_to_json(rt)), '[]'::jsonb)
  into v_recent_transactions
  from (
    select t.medicine_name, t.change_qty, t.resulting_qty, t.reason, t.created_at
    from public.medicine_inventory_transactions t
    order by t.created_at desc
    limit 20
  ) rt;

  return jsonb_build_object(
    'total_medicines', v_total_medicines,
    'total_stock', v_total_stock,
    'low_stock_count', v_low_stock_count,
    'expiring_count', v_expiring_count,
    'expired_count', v_expired_count,
    'category_breakdown', v_category_breakdown,
    'recent_transactions', v_recent_transactions
  );
end;
$$;

revoke all on function public.get_inventory_report() from public;
grant execute on function public.get_inventory_report() to authenticated;

