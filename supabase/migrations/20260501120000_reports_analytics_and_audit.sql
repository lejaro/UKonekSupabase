-- 6. RPC: Consultation analytics
-- ============================================================

create or replace function public.get_consultation_analytics(
  p_date_from date default (current_date - 30),
  p_date_to date default current_date
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_by_doctor jsonb;
  v_by_status jsonb;
  v_follow_ups_due jsonb;
begin
  select coalesce(jsonb_agg(row_to_json(d)), '[]'::jsonb)
  into v_by_doctor
  from (
    select
      coalesce(nullif(trim(concat_ws(' ', s.first_name, s.last_name)), ''), 'Doctor') as doctor_name,
      coalesce(s.doctor_specialization, '') as specialization,
      count(*) as consultation_count
    from public.consultations c
    left join public.staff s on s.id = c.doctor_staff_id
    where c.consulted_at::date between p_date_from and p_date_to
    group by 1, 2
    order by consultation_count desc
  ) d;

  select coalesce(jsonb_agg(row_to_json(st)), '[]'::jsonb)
  into v_by_status
  from (
    select c.consultation_status as status, count(*) as count
    from public.consultations c
    where c.consulted_at::date between p_date_from and p_date_to
    group by c.consultation_status
  ) st;

  select coalesce(jsonb_agg(row_to_json(f)), '[]'::jsonb)
  into v_follow_ups_due
  from (
    select
      c.id,
      coalesce(c.chief_complaint, c.diagnosis, '') as reason,
      c.follow_up_date,
      coalesce(nullif(trim(concat_ws(' ', cit.firstname, cit.surname)), ''), 'Patient') as patient_name,
      coalesce(nullif(trim(concat_ws(' ', s.first_name, s.last_name)), ''), 'Doctor') as doctor_name
    from public.consultations c
    left join public.citizens cit on cit.id = c.patient_citizen_id
    left join public.staff s on s.id = c.doctor_staff_id
    where c.follow_up_date is not null
      and c.follow_up_date between current_date and (current_date + 14)
    order by c.follow_up_date asc
    limit 20
  ) f;

  return jsonb_build_object(
    'by_doctor', v_by_doctor,
    'by_status', v_by_status,
    'follow_ups_due', v_follow_ups_due
  );
end;
$$;

revoke all on function public.get_consultation_analytics(date, date) from public;
grant execute on function public.get_consultation_analytics(date, date) to authenticated;
