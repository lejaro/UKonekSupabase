-- 5. RPC: Financial Summary
-- ============================================================

create or replace function public.get_financial_summary(
  p_date_from date default (current_date - 30),
  p_date_to date default current_date
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_total_income numeric;
  v_total_expense numeric;
  v_daily_breakdown jsonb;
  v_category_breakdown jsonb;
begin
  select coalesce(sum(case when t.transaction_type = 'income' then t.amount else 0 end), 0),
         coalesce(sum(case when t.transaction_type = 'expense' then t.amount else 0 end), 0)
  into v_total_income, v_total_expense
  from public.clinic_transactions t
  where t.transaction_date between p_date_from and p_date_to;

  select coalesce(jsonb_agg(row_to_json(d)), '[]'::jsonb)
  into v_daily_breakdown
  from (
    select
      t.transaction_date as date,
      coalesce(sum(case when t.transaction_type = 'income' then t.amount else 0 end), 0) as income,
      coalesce(sum(case when t.transaction_type = 'expense' then t.amount else 0 end), 0) as expense
    from public.clinic_transactions t
    where t.transaction_date between p_date_from and p_date_to
    group by t.transaction_date
    order by t.transaction_date asc
  ) d;

  select coalesce(jsonb_agg(row_to_json(c)), '[]'::jsonb)
  into v_category_breakdown
  from (
    select t.category, t.transaction_type,
           coalesce(sum(t.amount), 0) as total
    from public.clinic_transactions t
    where t.transaction_date between p_date_from and p_date_to
    group by t.category, t.transaction_type
    order by total desc
  ) c;

  return jsonb_build_object(
    'total_income', v_total_income,
    'total_expense', v_total_expense,
    'net_income', v_total_income - v_total_expense,
    'daily_breakdown', v_daily_breakdown,
    'category_breakdown', v_category_breakdown,
    'date_from', p_date_from,
    'date_to', p_date_to
  );
end;
$$;

revoke all on function public.get_financial_summary(date, date) from public;
grant execute on function public.get_financial_summary(date, date) to authenticated;

