-- Reports & Analytics: financial transactions table, patient statistics,
-- inventory reporting, consultation analytics, and audit logging.

-- ============================================================
-- 1. Clinic financial transactions
-- ============================================================

create table if not exists public.clinic_transactions (
  id bigint generated by default as identity primary key,
  transaction_type text not null,
  category text not null,
  amount numeric(12,2) not null,
  description text,
  reference_id text,
  transaction_date date not null default current_date,
  created_by_staff_id bigint references public.staff(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint clinic_transactions_type_valid check (transaction_type in ('income', 'expense')),
  constraint clinic_transactions_amount_positive check (amount >= 0),
  constraint clinic_transactions_category_non_empty check (length(trim(category)) > 0)
);

create index if not exists idx_clinic_transactions_date
  on public.clinic_transactions(transaction_date desc);
create index if not exists idx_clinic_transactions_type_date
  on public.clinic_transactions(transaction_type, transaction_date);

alter table public.clinic_transactions enable row level security;

drop policy if exists clinic_transactions_select_admin on public.clinic_transactions;
create policy clinic_transactions_select_admin
  on public.clinic_transactions
  for select
  using (
    public.is_admin()
    or exists (
      select 1 from public.staff s
      where s.auth_user_id = auth.uid()
        and lower(trim(coalesce(s.status, ''))) = 'active'
    )
  );

drop policy if exists clinic_transactions_insert_admin on public.clinic_transactions;
create policy clinic_transactions_insert_admin
  on public.clinic_transactions
  for insert
  with check (public.is_admin());

drop policy if exists clinic_transactions_update_admin on public.clinic_transactions;
create policy clinic_transactions_update_admin
  on public.clinic_transactions
  for update
  using (public.is_admin());

drop policy if exists clinic_transactions_delete_admin on public.clinic_transactions;
create policy clinic_transactions_delete_admin
  on public.clinic_transactions
  for delete
  using (public.is_admin());

grant select, insert, update, delete on public.clinic_transactions to authenticated;

-- Updated_at trigger
create or replace function public.set_clinic_transactions_updated_at()
returns trigger language plpgsql as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

drop trigger if exists trg_clinic_transactions_updated_at on public.clinic_transactions;
create trigger trg_clinic_transactions_updated_at
  before update on public.clinic_transactions
  for each row execute function public.set_clinic_transactions_updated_at();

-- ============================================================
-- 2. Audit log table
-- ============================================================

create table if not exists public.audit_log (
  id bigint generated by default as identity primary key,
  action text not null,
  entity_type text not null,
  entity_id text,
  details jsonb,
  performed_by_staff_id bigint references public.staff(id) on delete set null,
  performed_by_auth_uid uuid,
  ip_address text,
  created_at timestamptz not null default now()
);

create index if not exists idx_audit_log_created_at on public.audit_log(created_at desc);
create index if not exists idx_audit_log_entity on public.audit_log(entity_type, entity_id);
create index if not exists idx_audit_log_staff on public.audit_log(performed_by_staff_id);

alter table public.audit_log enable row level security;

drop policy if exists audit_log_select_admin on public.audit_log;
create policy audit_log_select_admin
  on public.audit_log
  for select
  using (public.is_admin());

drop policy if exists audit_log_insert_authenticated on public.audit_log;
create policy audit_log_insert_authenticated
  on public.audit_log
  for insert
  with check (true);

grant select, insert on public.audit_log to authenticated;

-- ============================================================
-- 3. RPC: Patient Statistics
-- ============================================================

create or replace function public.get_patient_statistics(
  p_date_from date default (current_date - 30),
  p_date_to date default current_date
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_result jsonb;
  v_total_consultations bigint;
  v_unique_patients bigint;
  v_today_consultations bigint;
  v_gender_dist jsonb;
  v_age_groups jsonb;
  v_top_diagnoses jsonb;
  v_daily_counts jsonb;
begin
  -- Total consultations in range
  select count(*) into v_total_consultations
  from public.consultations c
  where c.consulted_at::date between p_date_from and p_date_to;

  -- Unique patients
  select count(distinct c.patient_citizen_id) into v_unique_patients
  from public.consultations c
  where c.consulted_at::date between p_date_from and p_date_to
    and c.patient_citizen_id is not null;

  -- Today's consultations
  select count(*) into v_today_consultations
  from public.consultations c
  where c.consulted_at::date = current_date;

  -- Gender distribution
  select coalesce(jsonb_agg(row_to_json(g)), '[]'::jsonb)
  into v_gender_dist
  from (
    select coalesce(nullif(trim(cit.sex), ''), 'Unknown') as gender, count(*) as count
    from public.consultations c
    join public.citizens cit on cit.id = c.patient_citizen_id
    where c.consulted_at::date between p_date_from and p_date_to
    group by coalesce(nullif(trim(cit.sex), ''), 'Unknown')
    order by count desc
  ) g;

  -- Age group distribution
  select coalesce(jsonb_agg(row_to_json(a)), '[]'::jsonb)
  into v_age_groups
  from (
    select
      case
        when coalesce(cit.age, 0) <= 5 then '0-5 (Infant)'
        when coalesce(cit.age, 0) <= 12 then '6-12 (Child)'
        when coalesce(cit.age, 0) <= 17 then '13-17 (Adolescent)'
        when coalesce(cit.age, 0) <= 35 then '18-35 (Young Adult)'
        when coalesce(cit.age, 0) <= 59 then '36-59 (Adult)'
        else '60+ (Senior)'
      end as age_group,
      count(*) as count
    from public.consultations c
    join public.citizens cit on cit.id = c.patient_citizen_id
    where c.consulted_at::date between p_date_from and p_date_to
    group by 1
    order by count desc
  ) a;

  -- Top diagnoses
  select coalesce(jsonb_agg(row_to_json(d)), '[]'::jsonb)
  into v_top_diagnoses
  from (
    select coalesce(nullif(trim(c.diagnosis), ''), 'Unspecified') as diagnosis, count(*) as count
    from public.consultations c
    where c.consulted_at::date between p_date_from and p_date_to
      and nullif(trim(c.diagnosis), '') is not null
    group by coalesce(nullif(trim(c.diagnosis), ''), 'Unspecified')
    order by count desc
    limit 10
  ) d;

  -- Daily consultation counts
  select coalesce(jsonb_agg(row_to_json(dc)), '[]'::jsonb)
  into v_daily_counts
  from (
    select c.consulted_at::date as date, count(*) as count
    from public.consultations c
    where c.consulted_at::date between p_date_from and p_date_to
    group by c.consulted_at::date
    order by c.consulted_at::date asc
  ) dc;

  v_result := jsonb_build_object(
    'total_consultations', v_total_consultations,
    'unique_patients', v_unique_patients,
    'today_consultations', v_today_consultations,
    'gender_distribution', v_gender_dist,
    'age_groups', v_age_groups,
    'top_diagnoses', v_top_diagnoses,
    'daily_counts', v_daily_counts,
    'date_from', p_date_from,
    'date_to', p_date_to
  );

  return v_result;
end;
$$;

revoke all on function public.get_patient_statistics(date, date) from public;
grant execute on function public.get_patient_statistics(date, date) to authenticated;

