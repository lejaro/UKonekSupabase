drop policy if exists consultations_update_nurse_vitals on public.consultations;
create policy consultations_update_nurse_vitals
  on public.consultations
  for update
  using (
    exists (
      select 1 from public.staff s
      where s.auth_user_id = auth.uid()
        and lower(trim(coalesce(s.status, ''))) = 'active'
        and lower(trim(coalesce(s.role, ''))) in ('doctor', 'nurse')
    )
  )
  with check (
    exists (
      select 1 from public.staff s
      where s.auth_user_id = auth.uid()
        and lower(trim(coalesce(s.status, ''))) = 'active'
        and lower(trim(coalesce(s.role, ''))) in ('doctor', 'nurse')
    )
  );

grant update on public.consultations to authenticated;
